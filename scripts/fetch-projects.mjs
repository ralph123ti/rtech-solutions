import { existsSync, writeFileSync } from 'node:fs'

const USER = 'ralph123ti'
const OUT = new URL('../src/data/githubProjects.generated.ts', import.meta.url)

// GitHub topic -> name shown on the site (names must match src/data/techIcons.ts)
const TOPIC_NAMES = {
  react: 'React',
  typescript: 'TypeScript',
  javascript: 'JavaScript',
  tailwindcss: 'Tailwind CSS',
  vite: 'Vite',
  nodejs: 'Node.js',
  express: 'Express',
  mongodb: 'MongoDB',
  python: 'Python',
  html: 'HTML',
  css: 'CSS',
  'framer-motion': 'Framer Motion',
  ai: 'AI API',
  openai: 'AI API',
  api: 'API Integration',
}

function toTitle(name) {
  return name
    .replace(/[-_]+/g, ' ')
    .replace(/\b\w/g, (c) => c.toUpperCase())
}

// Make sure a website address always starts with https://
function toAbsoluteUrl(value) {
  const url = value.trim()
  return /^https?:\/\//i.test(url) ? url : `https://${url}`
}

// Your own screenshot wins; otherwise use an automatic screenshot of the live site
function pickImage(repoName, liveUrl) {
  const localFile = new URL(`../public/projects/${repoName}.png`, import.meta.url)
  if (existsSync(localFile)) return `/projects/${repoName}.png`
  if (liveUrl) {
    return `https://s.wordpress.com/mshots/v1/${encodeURIComponent(liveUrl)}?w=800&h=500`
  }
  return undefined
}

function write(projects) {
  const file = `// AUTO-GENERATED by scripts/fetch-projects.mjs. Do not edit by hand.
export interface GithubProject {
  title: string
  description: string
  status: 'in-progress' | 'completed'
  tech: string[]
  liveUrl?: string
  codeUrl: string
  image?: string
}

export const githubProjects: GithubProject[] = ${JSON.stringify(projects, null, 2)}
`
  writeFileSync(OUT, file)
}

async function main() {
  try {
    const headers = {
      Accept: 'application/vnd.github+json',
      'User-Agent': 'rtech-portfolio',
    }
    // Optional: a token only raises build-time rate limits. It never reaches the browser.
    if (process.env.GITHUB_TOKEN) {
      headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`
    }

    const res = await fetch(
      `https://api.github.com/users/${USER}/repos?per_page=100&sort=updated`,
      { headers },
    )
    if (!res.ok) throw new Error(`GitHub responded with ${res.status}`)
    const repos = await res.json()

    const projects = repos
      .filter(
        (r) =>
          !r.fork &&
          !r.archived &&
          Array.isArray(r.topics) &&
          r.topics.includes('portfolio'),
      )
      .map((r) => {
        const tech = r.topics.map((t) => TOPIC_NAMES[t]).filter(Boolean)
        if (tech.length === 0 && r.language) tech.push(r.language)

        const project = {
          title: toTitle(r.name),
          description: r.description || 'Project description coming soon.',
          status: r.topics.includes('in-progress') ? 'in-progress' : 'completed',
          tech: [...new Set(tech)],
          codeUrl: r.html_url,
        }
        if (r.homepage && r.homepage.trim()) {
          project.liveUrl = toAbsoluteUrl(r.homepage)
        }
        const image = pickImage(r.name, project.liveUrl)
        if (image) project.image = image
        return project
      })

    write(projects)
    console.log(`GitHub projects: found ${projects.length} tagged "portfolio".`)
  } catch (err) {
    console.warn(`GitHub projects: could not fetch (${err.message}).`)
    // Keep the last good file if there is one, otherwise start empty
    if (!existsSync(OUT)) write([])
  }
}

main()